"""
Aegis Saathi - authentication and role-based access (prototype-grade, dependency-free).

Roles
  senior       a phone / simulator: holds a per-senior DEVICE KEY issued at onboarding
  coordinator  logs in with coordinator code + PIN; sees ONLY their own seniors
  family       logs in with a FAMILY CODE the senior generated by consenting; sees one senior's summary
  ops          operations manager; sees aggregated numbers only, never an individual's records

Tokens are HMAC-SHA256 signed JSON (like a minimal JWT). The signing secret and the demo PINs live in
data/ and are created on first start. For production this module is the one to swap for a real
identity provider (OIDC) - every endpoint already goes through `who()` in server.py.
"""

import base64
import hashlib
import hmac
import json
import os
import secrets
import time
from dataclasses import dataclass
from typing import Any, Dict, Optional

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")
SECRET_FILE = os.path.join(DATA_DIR, "secret.key")
USERS_FILE = os.environ.get("AEGIS_AUTH_FILE", os.path.join(DATA_DIR, "auth.json"))

SESSION_TTL = 12 * 3600          # coordinator / ops / family sessions
ROLES = ("senior", "coordinator", "family", "ops")


@dataclass
class Principal:
    role: str
    sub: str                      # senior_id | coordinator code | "OPS-1" | family code
    scope: Optional[str] = None   # family: the one senior_id they may read


def _secret() -> bytes:
    os.makedirs(DATA_DIR, exist_ok=True)
    if not os.path.exists(SECRET_FILE):
        with open(SECRET_FILE, "w") as f:
            f.write(secrets.token_hex(32))
    with open(SECRET_FILE, "r") as f:
        return f.read().strip().encode()


def _b64(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _unb64(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def sign(payload: Dict[str, Any], ttl: Optional[int] = None) -> str:
    body = dict(payload)
    if ttl:
        body["exp"] = int(time.time()) + ttl
    raw = _b64(json.dumps(body, separators=(",", ":")).encode())
    sig = _b64(hmac.new(_secret(), raw.encode(), hashlib.sha256).digest())
    return f"{raw}.{sig}"


def verify(token: Optional[str]) -> Optional[Principal]:
    if not token or "." not in token:
        return None
    raw, sig = token.rsplit(".", 1)
    expect = _b64(hmac.new(_secret(), raw.encode(), hashlib.sha256).digest())
    if not hmac.compare_digest(sig, expect):
        return None
    try:
        body = json.loads(_unb64(raw))
    except Exception:
        return None
    if body.get("exp") and body["exp"] < time.time():
        return None
    if body.get("role") not in ROLES:
        return None
    return Principal(role=body["role"], sub=str(body.get("sub", "")), scope=body.get("scope"))


def issue_device_key(senior_id: str) -> str:
    """Long-lived key a senior's phone sends with every request (no expiry; revoke by re-registering)."""
    return sign({"role": "senior", "sub": senior_id})


def issue_session(role: str, sub: str, scope: Optional[str] = None) -> str:
    return sign({"role": role, "sub": sub, "scope": scope}, SESSION_TTL)


def principal_from_request(request) -> Optional[Principal]:
    """Bearer header, X-Device-Key header, or ?token= (needed for audio / WebSocket clients)."""
    h = request.headers.get("authorization", "")
    if h.lower().startswith("bearer "):
        p = verify(h[7:].strip())
        if p:
            return p
    p = verify(request.headers.get("x-device-key"))
    if p:
        return p
    return verify(request.query_params.get("token"))


# ------------------------------------------------------------------------------------ demo PINs
def load_credentials(coordinator_codes) -> Dict[str, Any]:
    """PINs are random per installation (created on first start) so nothing guessable ships in the repo."""
    os.makedirs(DATA_DIR, exist_ok=True)
    creds: Dict[str, Any] = {}
    if os.path.exists(USERS_FILE):
        try:
            with open(USERS_FILE, "r", encoding="utf-8") as f:
                creds = json.load(f)
        except Exception:
            creds = {}
    changed = False
    creds.setdefault("coordinators", {})
    for code in coordinator_codes:
        if code not in creds["coordinators"]:
            creds["coordinators"][code] = f"{secrets.randbelow(9000) + 1000}"
            changed = True
    if "ops" not in creds:
        creds["ops"] = {"OPS-1": f"{secrets.randbelow(9000) + 1000}"}
        changed = True
    if "gateway_key" not in creds:
        creds["gateway_key"] = secrets.token_hex(8)
        changed = True
    if changed:
        with open(USERS_FILE, "w", encoding="utf-8") as f:
            json.dump(creds, f, indent=2)
    return creds


def save_credentials(creds: Dict[str, Any]) -> None:
    """Written when a new care manager subscribes and gets a PIN."""
    os.makedirs(DATA_DIR, exist_ok=True)
    tmp = USERS_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(creds, f, indent=2)
    os.replace(tmp, USERS_FILE)


def check_pin(creds: Dict[str, Any], role: str, ident: str, pin: str) -> bool:
    table = creds.get("coordinators" if role == "coordinator" else "ops", {})
    expected = table.get(ident.upper())
    return bool(expected) and hmac.compare_digest(str(expected), str(pin).strip())
